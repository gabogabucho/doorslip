"""Doorslip — signed mailboxes for personal agents.

The name comes from *slipping a note under the door*: you leave something
behind, the recipient does not have to be present, they read it when they can,
and whoever is inside decides whether to open.

The scope is communication, not execution. `state` is data, `prose` is a
second-hand report, and neither is an instruction. A receiving agent never
executes what arrives in a message; it folds it into its own model and decides
on its own.
"""

